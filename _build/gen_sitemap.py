#!/usr/bin/env python3
"""Regenerate sitemap.xml with an honest lastmod for every page.

lastmod comes from the last commit that touched that page's SOURCE files, not
the generated HTML. Generated files change on every build; the source only
changes when the content does, which is what lastmod is supposed to mean.

Before the source is committed there is no history to read, so it falls back to
the generated page's own commit date, then to today.

  python3 _build/gen_sitemap.py            rewrite sitemap.xml
  python3 _build/gen_sitemap.py --check    report whether it is up to date
"""
import datetime, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC  = os.path.join(ROOT, "_build", "src")
BASE = "https://www.lohuissignature.nl/"
ORDER = ["index", "commissions", "chauffeur", "concierge", "journey", "retainer",
         "fleet", "the-house", "contact", "enquire", "faq", "privacy", "terms"]

HEADER = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by _build/gen_sitemap.py - do not edit by hand.
     Only canonical addresses belong here. The forwarding stubs (home.html,
     about.html, schiphol-chauffeur.html and the rest) each carry a canonical
     tag pointing at the real page, so listing them would ask search engines to
     index pages that have already told them not to. They are left out.
     lastmod is the last commit that changed that page's source. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
'''


def git_date(paths):
    paths = [p for p in paths if os.path.exists(p)]
    if not paths:
        return None
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--"] + paths,
                             cwd=ROOT, capture_output=True, text=True, timeout=20)
    except Exception:
        return None
    d = out.stdout.strip()
    return d or None


def lastmod(slug):
    src = [os.path.join(SRC, "pages", slug + ext)
           for ext in (".main.html", ".json", ".schema.jsonld")]
    return (git_date(src)
            or git_date([os.path.join(ROOT, slug + ".html")])
            or datetime.date.today().isoformat())


def build():
    rows = []
    for slug in ORDER:
        meta = json.load(open(os.path.join(SRC, "pages", slug + ".json"), encoding="utf-8"))
        loc = BASE if slug == "index" else BASE + slug + ".html"
        rows.append("  <url><loc>%s</loc><lastmod>%s</lastmod><priority>%s</priority></url>"
                    % (loc, lastmod(slug), meta["priority"]))
    return HEADER + "\n".join(rows) + "\n</urlset>\n"


def main():
    out = build()
    path = os.path.join(ROOT, "sitemap.xml")
    if "--check" in sys.argv:
        cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if cur == out:
            print("sitemap.xml is up to date")
            return 0
        print("sitemap.xml is STALE - run: python3 _build/gen_sitemap.py")
        return 1
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(out)
    print("wrote sitemap.xml (%d urls)" % len(ORDER))
    return 0


if __name__ == "__main__":
    sys.exit(main())
